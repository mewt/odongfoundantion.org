// ─── Language State ────────────────────────────────────────
let currentLang = localStorage.getItem('odong-lang') || 'en';

function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    localStorage.setItem('odong-lang', lang);
    
    // Update all translatable elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = translations[lang][key];
            } else {
                el.innerHTML = translations[lang][key];
            }
        }
    });
    
    // Update meta tags based on current page
    updateMetaTags(lang);
    
    // Update active language button
    document.querySelectorAll('.lang-btn').forEach(btn => {
        const isActive = btn.dataset.lang === lang;
        btn.classList.toggle('opacity-100', isActive);
        btn.classList.toggle('opacity-60', !isActive);
    });
}

function updateMetaTags(lang) {
    const page = getCurrentPage();
    const metaKeys = {
        'index': ['meta.home.title', 'meta.home.desc'],
        'about': ['meta.about.title', 'meta.about.desc'],
        'programs': ['meta.programs.title', 'meta.programs.desc'],
        'contact': ['meta.contact.title', 'meta.contact.desc'],
        'blog': ['meta.blog.title', 'meta.blog.desc'],
        '': ['meta.home.title', 'meta.home.desc'] // For root path
    };
    
    const pageKey = page || 'index';
    
    if (metaKeys[pageKey] && translations[lang]) {
        const [titleKey, descKey] = metaKeys[pageKey];
        
        // Update page title (handles both data-i18n and direct update)
        const titleElement = document.querySelector('title[data-i18n]');
        if (titleElement && translations[lang][titleKey]) {
            titleElement.textContent = translations[lang][titleKey];
        } else if (translations[lang][titleKey]) {
            document.title = translations[lang][titleKey];
        }
        
        // Update meta description (handles both data-i18n and direct update)
        let metaDesc = document.querySelector('meta[name="description"]');
        if (metaDesc && translations[lang][descKey]) {
            if (metaDesc.hasAttribute('data-i18n')) {
                metaDesc.content = translations[lang][descKey];
            } else {
                metaDesc.content = translations[lang][descKey];
            }
        } else if (translations[lang][descKey]) {
            // Create meta description if it doesn't exist
            metaDesc = document.createElement('meta');
            metaDesc.name = 'description';
            metaDesc.content = translations[lang][descKey];
            document.head.appendChild(metaDesc);
        }
    }
}

function getCurrentPage() {
    const path = window.location.pathname;
    const page = path.substring(path.lastIndexOf('/') + 1);
    return page || 'index';
}

